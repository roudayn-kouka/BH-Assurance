"""
Admin verdict → Kafka, without changing the review code.

The review paths (Express pilot in web/review-pilot, agent/utils/draft_review.py) commit
the verdict by moving a message from `pending` to `validated` / `rejected` and stamping
`reviewed_by` / `reviewed_at` in the same write (`is_modified` marks an edit in the
historical dashboard). This relay watches committed changes in MongoDB — so an event is
only emitted after a successful DB write — and publishes one idempotent `admin_verdict`
event per message that carries a `decision` (messages generated by Next-BH 2.0). The
reviewer's identity is not copied into the event. It also re-sends pending outbox events.

    python -m mlops.feedback.verdict_relay [--once] [--interval 10]

If the backend is later modified to publish the event itself (see docs/nextbh2/INTEGRATION.md),
the deterministic event_id makes both paths safe to run together.
"""

import argparse
import logging
import os
import sys
import time
from datetime import datetime, timezone
from typing import Optional

from mlops.common.events import (
    OUTBOX_COLLECTION,
    EventPublisher,
    admin_verdict_event,
    kafka_producer,
)

log = logging.getLogger("verdict_relay")

VERDICT_STATUSES = ("validated", "rejected")


def verdict_of(message: dict) -> Optional[str]:
    status = message.get("status")
    if status == "rejected":
        return "rejected"
    if status == "validated":
        return "edited" if message.get("is_modified") else "approved"
    return None


def relay_verdicts(messages, publisher: EventPublisher, limit: int = 500) -> int:
    query = {
        "status": {"$in": list(VERDICT_STATUSES)},
        "decision.decision_id": {"$exists": True},
        "verdict_event_id": {"$exists": False},
    }
    published = 0
    for msg in messages.find(query).limit(limit):
        verdict = verdict_of(msg)
        if verdict is None:
            continue
        # reviewed_at is written atomically with the decision (draft_review / review pilot)
        occurred = msg.get("reviewed_at") or msg.get("validated_at") or msg.get("updated_at")
        if isinstance(occurred, datetime) and occurred.tzinfo is None:
            occurred = occurred.replace(tzinfo=timezone.utc)  # MongoDB dates are UTC
        event = admin_verdict_event(
            msg["decision"], str(msg["_id"]), msg.get("conversation_id"), verdict,
            reason_code=msg.get("rejection_reason"),
            occurred_at=occurred.isoformat() if hasattr(occurred, "isoformat") else None,
        )
        publisher.publish(event)  # lands in the outbox even if Kafka is down
        # mark only if still unmarked: concurrent relays can't double-mark
        messages.update_one(
            {"_id": msg["_id"], "verdict_event_id": {"$exists": False}},
            {"$set": {"verdict_event_id": event.event_id,
                      "verdict_published_at": datetime.now(timezone.utc)}},
        )
        published += 1
    return published


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--once", action="store_true")
    parser.add_argument("--interval", type=float, default=10.0)
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(name)s] %(message)s")

    from pymongo import MongoClient

    db = MongoClient(os.getenv("MONGODB_URI", "mongodb://localhost:27017/BH")).get_database()
    try:
        producer = kafka_producer(os.getenv("KAFKA_BOOTSTRAP_SERVERS", "localhost:9092"))
    except Exception as e:
        log.warning("Kafka unavailable (%s): events stay in the outbox", e)
        producer = None
    publisher = EventPublisher(db[OUTBOX_COLLECTION],
                               os.getenv("DECISION_EVENTS_TOPIC", "decision_events"), producer)
    while True:
        n = relay_verdicts(db["messages"], publisher)
        resent = publisher.relay_outbox()
        if n or resent:
            log.info("verdicts published: %d, outbox re-sent: %d", n, resent)
        if args.once:
            return 0
        time.sleep(args.interval)


if __name__ == "__main__":
    sys.exit(main())
